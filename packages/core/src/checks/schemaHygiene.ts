import { DiagnosticFinding, DiagnosticSnapshot } from '../types.js';

export function checkSchemaHygiene(snapshot: DiagnosticSnapshot): DiagnosticFinding | null {
  const extensionsInPublic = snapshot.extensions.filter(
    (e) => e.schema.toLowerCase() === 'public'
  );

  const bloatTables = snapshot.tables.filter((t) => {
    if (t.deadTuples && t.liveTuples && t.deadTuples > 1000) {
      const deadRatio = t.deadTuples / (t.deadTuples + t.liveTuples);
      return deadRatio > 0.2; // >20% dead tuples
    }
    return false;
  });

  const unusedIndexes = snapshot.indexes.filter((idx) => {
    return (
      !idx.isPrimary &&
      !idx.isUnique &&
      idx.scans === 0 &&
      (idx.sizeBytes || 0) > 1024 * 1024 // >1MB unused index
    );
  });

  if (
    extensionsInPublic.length === 0 &&
    bloatTables.length === 0 &&
    unusedIndexes.length === 0
  ) {
    return null;
  }

  const affectedObjects: {
    schema?: string;
    name: string;
    type: 'extension' | 'table' | 'index';
    detail: string;
  }[] = [];

  for (const ext of extensionsInPublic) {
    affectedObjects.push({
      schema: 'public',
      name: ext.name,
      type: 'extension',
      detail: `Extension installed into "public" schema instead of "extensions". Pollutes PostgREST auto-generated OpenAPI schema and client types.`,
    });
  }

  for (const t of bloatTables) {
    const total = (t.deadTuples || 0) + (t.liveTuples || 0);
    const deadPct = Math.round(((t.deadTuples || 0) / total) * 100);
    affectedObjects.push({
      schema: t.schema,
      name: t.name,
      type: 'table',
      detail: `High table bloat: ${deadPct}% dead tuples (${t.deadTuples} dead out of ${total} total). Ineffective autovacuum is degrading scan performance.`,
    });
  }

  for (const idx of unusedIndexes) {
    const mb = ((idx.sizeBytes || 0) / (1024 * 1024)).toFixed(1);
    affectedObjects.push({
      schema: idx.schema,
      name: idx.name,
      type: 'index',
      detail: `Unused index on ${idx.table} (${mb} MB, 0 scans recorded). Consumes disk space and slows down INSERT/UPDATE operations.`,
    });
  }

  const fixSqlStatements: string[] = [];

  for (const ext of extensionsInPublic) {
    // Note: Some extensions like postgis or vector support ALTER EXTENSION ... SET SCHEMA extensions
    fixSqlStatements.push(
      `-- Move extension "${ext.name}" from public to extensions schema:\n` +
      `CREATE SCHEMA IF NOT EXISTS extensions;\n` +
      `ALTER EXTENSION "${ext.name}" SET SCHEMA extensions;`
    );
  }

  for (const t of bloatTables) {
    fixSqlStatements.push(
      `-- Reclaim bloat space on ${t.schema}.${t.name}:\n` +
      `VACUUM (VERBOSE, ANALYZE) "${t.schema}"."${t.name}";`
    );
  }

  for (const idx of unusedIndexes) {
    fixSqlStatements.push(
      `-- Drop unused index "${idx.name}" on ${idx.schema}.${idx.table}:\n` +
      `DROP INDEX CONCURRENTLY IF EXISTS "${idx.schema}"."${idx.name}";`
    );
  }

  return {
    id: 'SCHEMA_BLOAT_AND_EXTENSIONS_HYGIENE',
    category: 'hygiene',
    severity: 'medium',
    title: 'Schema Hygiene: Extensions in Public, Table Bloat, and Unused Indexes',
    summary: `Found ${extensionsInPublic.length} extension(s) in public schema, ${bloatTables.length} bloated table(s), and ${unusedIndexes.length} unused index(es).`,
    whyItClogsSupport:
      'Installing extensions like `pgvector` or `uuid-ossp` directly in `public` automatically generates API endpoints in PostgREST and clutters TypeScript types generated by supabase-gen-types. Meanwhile, dead tuples from frequent updates without aggressive autovacuum degrade scan speeds, and unused indexes silently eat IOPS on every write.',
    affectedObjects,
    remediationExplanation:
      '1. Keep the `public` schema reserved strictly for application tables. Install extensions into the dedicated `extensions` schema.\n' +
      '2. Run `VACUUM ANALYZE` or tune autovacuum vacuum scale factor on frequently updated tables.\n' +
      '3. Safely drop unused indexes using `DROP INDEX CONCURRENTLY`.',
    fixSql: fixSqlStatements.join('\n\n'),
    documentationUrl: 'https://supabase.com/docs/guides/database/database-linter#extension_in_public',
    metadata: {
      linterRules: ['0014_extension_in_public', '0005_unused_index'],
      extensionsInPublicCount: extensionsInPublic.length,
      bloatTablesCount: bloatTables.length,
      unusedIndexesCount: unusedIndexes.length,
    },
  };
}

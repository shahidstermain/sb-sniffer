import { DiagnosticFinding, DiagnosticReport, DiagnosticSnapshot } from '../types.js';

export function formatReportMarkdown(report: DiagnosticReport): string {
  const { healthScore, grade, summary, findings } = report;

  const lines: string[] = [];

  lines.push(`# 🕵️‍♂️ Supabase Diagnostic & Health Report`);
  lines.push(`\n**Generated At:** ${new Date(report.timestamp).toUTCString()}`);
  lines.push(`**Source:** \`${report.source}\`\n`);

  lines.push(`## 🎯 Overall Health Score: **${healthScore}/100** (Grade: **${grade}**)`);
  lines.push(`\n| Severity | Count |`);
  lines.push(`|---|---|`);
  lines.push(`| 🔴 Critical | **${summary.criticalCount}** |`);
  lines.push(`| 🟠 High | **${summary.highCount}** |`);
  lines.push(`| 🟡 Medium | **${summary.mediumCount}** |`);
  lines.push(`| 🔵 Info | **${summary.infoCount}** |`);
  lines.push(`| **Total** | **${summary.totalFindings}** |\n`);

  lines.push(`---\n`);
  lines.push(`## 🚨 Diagnostic Findings\n`);

  if (findings.length === 0) {
    lines.push(`✅ **No critical or high-priority issues detected! Your Supabase database is in top shape.**`);
  }

  for (let i = 0; i < findings.length; i++) {
    const f = findings[i];
    const badge =
      f.severity === 'critical'
        ? '🔴 CRITICAL'
        : f.severity === 'high'
        ? '🟠 HIGH'
        : f.severity === 'medium'
        ? '🟡 MEDIUM'
        : '🔵 INFO';

    lines.push(`### ${i + 1}. [${badge}] ${f.title}`);
    lines.push(`\n**Check ID:** \`${f.id}\` | **Category:** \`${f.category}\`\n`);
    lines.push(`> **Summary:** ${f.summary}\n`);

    lines.push(`#### ⚠️ Why This Clogs the Supabase Support Queue:`);
    lines.push(`${f.whyItClogsSupport}\n`);

    if (f.affectedObjects.length > 0) {
      lines.push(`#### 📌 Affected Database Objects:`);
      lines.push(`| Object | Type | Details |`);
      lines.push(`|---|---|---|`);
      for (const obj of f.affectedObjects) {
        lines.push(`| \`${obj.name}\` | \`${obj.type}\` | ${obj.detail || ''} |`);
      }
      lines.push('');
    }

    lines.push(`#### 🛠️ Remediation:`);
    lines.push(`${f.remediationExplanation}\n`);

    if (f.fixSql) {
      lines.push('```sql');
      lines.push(f.fixSql);
      lines.push('```\n');
    }

    if (f.documentationUrl) {
      lines.push(`📖 [Supabase Documentation](${f.documentationUrl})\n`);
    }

    lines.push(`---\n`);
  }

  return lines.join('\n');
}

export function formatFixAllSql(findings: DiagnosticFinding[]): string {
  const sqlBlocks: string[] = [];

  sqlBlocks.push(`-- =========================================================`);
  sqlBlocks.push(`-- SUPABASE DIAGNOSTIC REMEDIATION SCRIPT`);
  sqlBlocks.push(`-- Auto-generated by sb-sniffer`);
  sqlBlocks.push(`-- Review each block before applying to production database.`);
  sqlBlocks.push(`-- =========================================================\n`);

  for (const f of findings) {
    if (f.fixSql && f.fixSql.trim().length > 0) {
      sqlBlocks.push(`-- [${f.severity.toUpperCase()}] ${f.title} (${f.id})`);
      sqlBlocks.push(f.fixSql.trim());
      sqlBlocks.push('\n');
    }
  }

  return sqlBlocks.join('\n');
}

/**
 * Generates a production-safe migration script from findings:
 * - Converts CREATE INDEX into CREATE INDEX CONCURRENTLY IF NOT EXISTS to avoid table write locks.
 * - Strips BEGIN/COMMIT wrappers around CONCURRENTLY statements (Postgres forbids CONCURRENTLY inside transactions).
 */
export function formatSafeMigrationSql(findings: DiagnosticFinding[]): string {
  const base = formatFixAllSql(findings);
  return base
    .replace(
      /CREATE INDEX\s+(?!CONCURRENTLY\b)(?:IF NOT EXISTS\s+)?/gi,
      'CREATE INDEX CONCURRENTLY IF NOT EXISTS '
    )
    .replace(/^\s*(?:BEGIN|COMMIT)\s*;\s*$/gim, '')
    .replace(/\n{3,}/g, '\n\n');
}

/**
 * Detailed, self-contained export meant to be attached to an AI chat (Gemini, ChatGPT, DeepSeek...).
 * Includes an assistant prompt, every finding in full, and the supporting snapshot context
 * (schema, policies, indexes, connections, slow queries, logs, app-code hits).
 * Credentials are never included; connection strings in text are redacted.
 */
export function formatReportForAI(report: DiagnosticReport, snapshot?: DiagnosticSnapshot): string {
  const L: string[] = [];
  const redact = (s: string) =>
    String(s ?? '')
      .replace(/(postgres(?:ql)?:\/\/[^:\s]+:)[^@\s]+@/gi, '$1***@')
      .replace(/eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, '<JWT_REDACTED>');
  const json = (v: unknown) => redact(JSON.stringify(v, null, 2));
  const cap = <T,>(arr: T[] | undefined, n: number) => (arr ?? []).slice(0, n);
  const more = (arr: unknown[] | undefined, n: number) =>
    arr && arr.length > n ? `\n_(${arr.length - n} more omitted)_` : '';

  L.push('# Supabase Diagnostic Export (AI-ready)');
  L.push('');
  L.push('## Instructions for the AI assistant');
  L.push(
    'You are a senior Postgres / Supabase engineer. The user ran SB Sniffer on their project and attached this report. ' +
      'Use ONLY the data below. Start by briefly summarising the overall health and the top 3 risks, then wait for the user\'s questions. ' +
      'When explaining a finding: give root cause, impact, the exact fix (review any SQL before running; prefer a staging DB), and how to verify it. ' +
      'If information is missing, ask for it rather than guessing. Reference findings by their ID (e.g. `RLS_UNWRAPPED_AUTH_FUNC`).'
  );
  L.push('');
  L.push('## Overview');
  L.push(`- Generated: ${report.timestamp}`);
  L.push(`- Source: ${report.source}`);
  if (snapshot?.projectName) L.push(`- Project: ${snapshot.projectName}`);
  L.push(`- Health score: ${report.healthScore}/100 (grade ${report.grade})`);
  const s = report.summary;
  L.push(`- Findings: ${s.totalFindings} total — critical ${s.criticalCount}, high ${s.highCount}, medium ${s.mediumCount}, info ${s.infoCount}`);
  L.push('');
  L.push('### Category scores');
  L.push('| Category | Score | Critical | High | Medium | Info |');
  L.push('|---|---|---|---|---|---|');
  for (const [cat, c] of Object.entries(report.categoryScores ?? {})) {
    L.push(`| ${cat} | ${c.score} | ${c.criticalCount} | ${c.highCount} | ${c.mediumCount} | ${c.infoCount} |`);
  }
  L.push('');
  L.push('### Findings index');
  report.findings.forEach((f, i) => L.push(`${i + 1}. [${f.severity.toUpperCase()}] \`${f.id}\` — ${f.title}`));
  L.push('');
  L.push('## Findings (detailed)');
  report.findings.forEach((f, i) => {
    L.push(`### ${i + 1}. ${f.title}`);
    L.push(`- ID: \`${f.id}\``);
    L.push(`- Severity: ${f.severity}`);
    L.push(`- Category: ${f.category}`);
    L.push(`- Summary: ${redact(f.summary)}`);
    L.push(`- Why it matters: ${redact(f.whyItClogsSupport)}`);
    if (f.documentationUrl) L.push(`- Docs: ${f.documentationUrl}`);
    if (f.affectedObjects.length) {
      L.push('- Affected objects:');
      for (const o of f.affectedObjects) {
        L.push(`  - \`${o.schema ? o.schema + '.' : ''}${o.name}\` (${o.type})${o.detail ? ': ' + redact(o.detail) : ''}`);
      }
    }
    L.push(`- Remediation: ${redact(f.remediationExplanation)}`);
    if (f.fixSql) L.push('- Suggested fix SQL:', '```sql', redact(f.fixSql), '```');
    if (f.metadata && Object.keys(f.metadata).length) L.push('- Metadata:', '```json', json(f.metadata), '```');
    L.push('');
  });

  if (snapshot) {
    L.push('## Supporting context (from the analysed snapshot)');
    L.push(
      `Counts: ${snapshot.tables.length} tables, ${snapshot.policies.length} RLS policies, ${snapshot.indexes.length} indexes, ` +
        `${snapshot.foreignKeys.length} foreign keys, ${snapshot.triggers.length} triggers, ${snapshot.extensions.length} extensions.`
    );
    L.push('');
    L.push('### Tables');
    L.push('| Table | RLS | Replica identity | Est. rows | Dead tuples |');
    L.push('|---|---|---|---|---|');
    for (const t of cap(snapshot.tables, 200))
      L.push(`| ${t.schema}.${t.name} | ${t.rlsEnabled ? 'on' : 'OFF'} | ${t.replicaIdentity} | ${t.totalRowsEstimate ?? t.liveTuples ?? '?'} | ${t.deadTuples ?? '?'} |`);
    L.push(more(snapshot.tables, 200));
    L.push('');
    L.push('### RLS policies');
    for (const p of cap(snapshot.policies, 200))
      L.push(`- \`${p.schema}.${p.table}\` **${p.name}** ${p.command} ${p.permissive} roles=[${p.roles.join(',')}] USING: \`${redact(p.qual ?? '')}\` CHECK: \`${redact(p.withCheck ?? '')}\``);
    L.push(more(snapshot.policies, 200));
    L.push('');
    L.push('### Indexes');
    for (const x of cap(snapshot.indexes, 200))
      L.push(`- \`${x.schema}.${x.table}\` ${x.name} (${x.columns.join(', ')})${x.isPrimary ? ' PK' : x.isUnique ? ' UNIQUE' : ''}${x.isValid === false ? ' INVALID' : ''}${x.scans !== undefined ? ` scans=${x.scans}` : ''}`);
    L.push(more(snapshot.indexes, 200));
    L.push('');
    L.push('### Foreign keys');
    for (const k of cap(snapshot.foreignKeys, 200))
      L.push(`- ${k.schema}.${k.table}(${k.columns.join(',')}) -> ${k.foreignSchema}.${k.foreignTable}(${k.foreignColumns.join(',')})`);
    L.push(more(snapshot.foreignKeys, 200));
    L.push('');
    L.push('### Triggers');
    for (const t of cap(snapshot.triggers, 100)) {
      L.push(`- ${t.schema}.${t.table}: ${t.name} ${t.timing} ${t.event} -> ${t.functionSchema}.${t.functionName}${t.isSecurityDefiner ? ' [SECURITY DEFINER]' : ''}`);
      if (t.functionDef) L.push('```sql', redact(t.functionDef).slice(0, 3000), '```');
    }
    L.push('');
    if (snapshot.extensions.length)
      L.push('### Extensions', snapshot.extensions.map((e) => `${e.name}@${e.version}`).join(', '), '');
    if (snapshot.connections) L.push('### Connections', '```json', json(snapshot.connections), '```', '');
    if (snapshot.statStatements?.length) {
      L.push('### Top queries by total time (pg_stat_statements)');
      const top = [...snapshot.statStatements].sort((a, b) => b.totalExecTimeMs - a.totalExecTimeMs);
      for (const q of top.slice(0, 20))
        L.push(`- calls=${q.calls} mean=${q.meanExecTimeMs.toFixed(1)}ms total=${q.totalExecTimeMs.toFixed(0)}ms cacheHit=${q.cacheHitRatio ?? '?'}\n  \`${redact(q.query).replace(/\s+/g, ' ').slice(0, 500)}\``);
      L.push('');
    }
    if (snapshot.statTables?.length) {
      L.push('### Table stats (bloat / scans)');
      for (const t of cap(snapshot.statTables, 50))
        L.push(`- ${t.schema}.${t.table}: seqScan=${t.seqScan} idxScan=${t.idxScan} live=${t.nLiveTup} dead=${t.nDeadTup} (${(t.deadTupleRatio * 100).toFixed(1)}%)`);
      L.push('');
    }
    if (snapshot.storageBuckets?.length)
      L.push('### Storage buckets', snapshot.storageBuckets.map((b) => `${b.name}${b.public ? ' (public)' : ''}`).join(', '), '');
    if (snapshot.realtimeTables?.length) {
      L.push('### Realtime tables');
      for (const r of snapshot.realtimeTables)
        L.push(`- ${r.schema}.${r.table} published=${r.inPublication} replica=${r.replicaIdentity} rls=${r.rlsEnabled}`);
      L.push('');
    }
    if (snapshot.logs?.length) {
      L.push('### Log entries (errors/warnings first)');
      const order = { fatal: 0, error: 1, warning: 2, info: 3, debug: 4 } as const;
      const logs = [...snapshot.logs].sort((a, b) => order[a.level] - order[b.level]);
      for (const l of logs.slice(0, 100))
        L.push(`- ${l.timestamp} [${l.service}/${l.level}]${l.matchedCheckId ? ` (${l.matchedCheckId})` : ''} ${redact(l.message).slice(0, 600)}`);
      L.push(more(snapshot.logs, 100), '');
    }
    if (snapshot.appCode) {
      L.push(`### App code scan (${snapshot.appCode.scannedFiles} files scanned)`);
      for (const it of cap(snapshot.appCode.items, 100))
        L.push(`- \`${it.file}:${it.line}\` [${it.kind}] ${redact(it.detail)}\n  \`${redact(it.snippet).trim().slice(0, 300)}\``);
      L.push(more(snapshot.appCode.items, 100), '');
    }
  }

  L.push('---');
  L.push('End of report. Suggested first prompts: "Summarise the biggest risks", "Walk me through fixing the critical findings in order", "Why is `<finding id>` happening and how do I verify the fix?"');
  return L.join('\n');
}
